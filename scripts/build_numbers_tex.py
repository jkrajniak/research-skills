#!/usr/bin/env python3
"""Generate numbers.tex from the paper's numbers.json registry.

    python3 scripts/build_numbers_tex.py paper/numbers.json paper/numbers.tex

Every entry becomes a value the manuscript pulls in with \\num{key}, so a
number is typed once (in the registry) and cannot drift between sections.

Registry format (JSON object, key -> entry):

    "dodecane.peak_T": {
      "value": 1913,            # number, required
      "fmt": "{:.0f}",          # Python format, default "{:g}"
      "tex": "seven",           # optional literal; overrides value/fmt/unit
      "unit": "K",              # optional; appended as \\,K (math-safe, siunitx-free)
      "source": "experiments/20260508_dodecane_ramp.md",   # required
      "sha256": "<archive hash>"                           # optional but encouraged
    }

Stdlib only. Exit code 1 on a malformed registry.
"""
import json
import sys
from pathlib import Path

UNIT_SEP = r"\,"


def render(entry):
    if "tex" in entry:  # literal override, e.g. "seven" for a count written in words
        return entry["tex"]
    fmt = entry.get("fmt", "{:g}")
    text = fmt.format(entry["value"])
    # Typographic minus and thousands thin-space, so tables and prose agree.
    text = text.replace("-", "$-$") if text.startswith("-") else text
    unit = entry.get("unit")
    if unit:
        text += UNIT_SEP + unit
    return text


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    src, dst = Path(argv[1]), Path(argv[2])
    registry = json.loads(src.read_text())
    problems = []
    lines = [
        "%% Generated by build_numbers_tex.py from %s. Do not edit." % src.name,
        r"\makeatletter",
        r"\newcommand{\num}[1]{\@ifundefined{num@#1}{\textbf{??#1??}}"
        r"{\csname num@#1\endcsname}}",
    ]
    for key, entry in sorted(registry.items()):
        if key.startswith("_"):
            continue  # comment / metadata keys
        if "value" not in entry:
            problems.append("%s: missing 'value'" % key)
            continue
        if not entry.get("source"):
            problems.append("%s: missing 'source' (every number needs provenance)" % key)
            continue
        lines.append(
            r"\expandafter\gdef\csname num@%s\endcsname{%s}" % (key, render(entry))
        )
    lines.append(r"\makeatother")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    dst.write_text("\n".join(lines) + "\n")
    print("wrote %s (%d numbers)" % (dst, len(lines) - 4))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
